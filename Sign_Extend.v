module Sign_Extend(
    input  [31:0] In,
    input  [2:0]  ImmSrc,
    output reg [31:0] Imm_Ext
);

    always @(*) begin
        case (ImmSrc)

            // -------------------------
            // I-type: imm[31:20]
            // -------------------------
            3'b000: Imm_Ext = {{20{In[31]}}, In[31:20]};

            // -------------------------
            // S-type: imm[31:25 | 11:7]
            // -------------------------
            3'b001: Imm_Ext = {{20{In[31]}}, In[31:25], In[11:7]};

            // -------------------------
            // B-type (branch)
            // imm[12 | 10:5 | 4:1 | 11 | 0]
            // -------------------------
            3'b010: Imm_Ext = {{19{In[31]}},
                                In[31],       // imm[12]
                                In[7],        // imm[11]
                                In[30:25],    // imm[10:5]
                                In[11:8],     // imm[4:1]
                                1'b0};        // imm[0]

            // -------------------------
            // U-type (LUI, AUIPC)
            // imm[31:12] << 12
            // -------------------------
            3'b011: Imm_Ext = {In[31:12], 12'b0};

            // -------------------------
            // J-type (JAL)
            // imm[20 | 10:1 | 11 | 19:12 | 0]
            // -------------------------
            3'b100: Imm_Ext = {{11{In[31]}},
                                In[31],       // imm[20]
                                In[19:12],    // imm[19:12]
                                In[20],       // imm[11]
                                In[30:21],    // imm[10:1]
                                1'b0};        // imm[0]

            default: Imm_Ext = 32'b0;
        endcase
    end

endmodule
